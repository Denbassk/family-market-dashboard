# -*- coding: utf-8 -*-
"""Подтверждённые склейки контрагентов: одно юрлицо под несколькими именами.

ПОЧЕМУ ЭТО СПИСОК РУКАМИ, А НЕ ПРАВИЛО. Соблазн склеивать по имени без скобки
(«Союз (Оболонь)» + «Союз (Наш Сік)» -> «Союз») даёт красивую цифру и НЕВЕРЕН:
«Арсенал ПК (Моршин)», «(Шейк)» и «(Азнаурі)» — один дистрибьютор, но в базе это
отдельные контрагенты с отдельными условиями сотрудничества, и объединять их нельзя.
А переименование юрлица по имени не видно вообще. Поэтому источник правды здесь —
решение владельца, а код только приносит кандидатов (детектор — см. `mem:supplier_catalog_manual`).

КАК НАХОДИЛИ КАНДИДАТОВ. У пары контрагентов общие штрих-коды, при этом один перестал
приходить, а второй начал. Владелец подтвердил 7 пар из 8 (2026-09-04); восьмую —
«Метро Кеш Енд Кері Україна» -> «ФОП Протопопов», 6 общих позиций на 106 тыс ₴ —
отклонил: это разные фирмы, товар просто перешёл.

ЧТО ДАЁТ. Имён: 127 контрагентов -> 120 юрлиц. Доля продаж, посчитанная без разнесения
(колонка «Точно» в карточке «Поставщики»): 79,1% -> 85,2%, то есть +17,5 млн ₴ выручки
перестают быть «разнесёнными».

КАК ДОПОЛНЯТЬ. Добавить строку `'старое имя': 'действующее имя'`. Действующее имя должно
существовать в приходах ровно так, как оно написано в Торгсофте, иначе склейка создаст
третье имя-призрак — это ловит тест `supplierSuite` в tests/check_dashboard.js.
"""

# старое имя из накладной -> действующее юрлицо
RENAMES = {
    "Трейдінг Продакт Компані": "Алко Трейдінг",                      # с июля 2026, 41 общая позиция (100%)
    "СТВ Схід (Корона)":        "ТОВ СТВ Дистрибюшн (Корона)",        # с июня, 62 позиции (85%)
    "Українська Злагода":       "Промтехнорент",                      # с апреля, 32 позиции (97%)
    "СТВ Схід (Якобз)":         "ТОВ СТВ Дистрибюшн (Якобз)",         # с июня, 36 позиций (97%)
    "СТВ Схід (Бащінський)":    "ТОВ СТВ Дистрибюшн (Бащинський)",    # с июня, 34 позиции (83%)
    "Гермес":                   "Торгівельна Компанія Юпітер",        # с апреля, 27 позиций (100%)
    "БІР (Ранок+Алкоголь)":     "ПП Продбаза 1",                      # с мая, 17 позиций (100%)
}

# Отклонено владельцем — держим здесь, чтобы кандидат не всплыл снова как «новый»:
REJECTED = {
    "Метро Кеш Енд Кері Україна": "ФОП Протопопов",   # разные фирмы, товар просто перешёл
}


def entity(name):
    """Действующее юрлицо для имени контрагента. Незнакомые возвращаются как есть."""
    return RENAMES.get((name or "").strip(), (name or "").strip())


def sql_case(col="supplier_ts"):
    """Готовое выражение CASE ... END: имя контрагента -> юрлицо."""
    if not RENAMES:
        return col
    body = " ".join("WHEN {c}='{k}' THEN '{v}'".format(c=col, k=k, v=v) for k, v in RENAMES.items())
    return "CASE {b} ELSE {c} END".format(b=body, c=col)
