#!/usr/bin/env python3
"""Ручные настройки по возвратам поставщикам.

ФИЗОБМЕН vs ДЕНЕЖНЫЙ ВОЗВРАТ
----------------------------
В данных Торгсофта НЕТ признака, отличающего реальный возврат (поставщик отдаёт деньги)
от физического обмена (поставщик забирает просрочку и привозит свежий товар бесплатно).
Проверено на данных 2026:
  * встречный приход по «обменным» документам не заводится вообще
    (нулевых/бесплатных приходов от реальных поставщиков — 0, все 1745 нулевых строк
     идут от служебного поставщика «Магазин»);
  * `is_prosrok` в torgsoft_outgoing_ref — это просто признак «магазин называется *-Просрок»,
    он не отличает обмен от возврата;
  * supplier_conditions.returns_text заполнен вручную и содержит подсказку только у одного
    поставщика («частично обмен» у УДК).

Поэтому список обменных поставщиков ведётся ЗДЕСЬ, руками.
Имена — КАНОНИЧЕСКИЕ (как в assortment_matrix_full / фильтре «Поставщик» на дашборде).
Возвраты таких поставщиков считаются, но помечаются флагом обмена и показываются
отдельной строкой «в т.ч. обмен», а не как возвращённые деньги.
"""

# Поставщики, у которых возврат просрочки фактически является физобменом (товар за товар).
# Заполнять по мере подтверждения от закупок. Пример: EXCHANGE_SUPPLIERS = {"Роганський МК", "УДК"}
EXCHANGE_SUPPLIERS = set()

# Отдельно: пары (поставщик, магазин), если обмен действует только по конкретной точке.
EXCHANGE_PAIRS = set()

# Классификация точек в потоке возвратов.
PROSROK_STORES = {"Магазины-Просрок", "Полевая-Просрок"}
WAREHOUSE_STORES = {"Полевая-Склад", "Производство", "Професорська 12"}


def store_class(store_raw, in_keep):
    """retail — торговая точка сети; prosrok — просрочка; wh — склад/опт/прочее."""
    if store_raw in PROSROK_STORES:
        return "prosrok"
    if store_raw in WAREHOUSE_STORES:
        return "wh"
    return "retail" if in_keep else "wh"


def is_exchange(supplier, store):
    return supplier in EXCHANGE_SUPPLIERS or (supplier, store) in EXCHANGE_PAIRS
