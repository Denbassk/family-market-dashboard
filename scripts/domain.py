def canon(store):
    """Каноническое имя точки. Незнакомые (служебные) возвращаются как есть."""
    s = (store or "").strip()
    return NORM.get(s, s)


def sql_case(col="store"):
    """Тело CASE для нормализации в SQL — БЕЗ слов CASE/END, как это уже принято в скриптах.
    Сравнение точное (без TRIM), чтобы результат совпадал с прежним кодом до знака:
    выборка всё равно ограничена sql_keep(), туда мусор с пробелами не попадает."""
    return " ".join(f"WHEN {col}='{k}' THEN '{v}'" for k, v in NORM.items())


def sql_case_full(col="store"):
    """Готовое выражение с ELSE: незнакомые имена (склад, просрочка) остаются как есть.
    Нужно там, где выборка НЕ ограничена списком keep, — например в снимке остатков."""
    cases = " ".join(f"WHEN TRIM({col})='{k}' THEN '{v}'" for k, v in NORM.items())
    return f"CASE {cases} ELSE TRIM({col}) END"


def sql_keep(col=None):
    """Список СЫРЫХ имён для WHERE store IN (...). Совпадает с ключами NORM."""
    return "(" + ",".join(f"'{k}'" for k in NORM) + ")"
